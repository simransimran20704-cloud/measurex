import React from 'react';
import { useHistoryStore } from '../../stores/historyStore';
import { useProjectStore } from '../../stores/projectStore';
import { useCalibrationStore } from '../../stores/calibrationStore';
import { useAppStore } from '../../stores/appStore';
import { useAuthStore } from '../../stores/authStore';
import { jsPDF } from 'jspdf';
import {
  Download,
  FileText,
  FileSpreadsheet,
  Code,
  CheckCircle2,
  Calendar,
  Sparkles,
} from 'lucide-react';

export const ExportCenterView: React.FC = () => {
  const { items } = useHistoryStore();
  const { projects } = useProjectStore();
  const { profile } = useCalibrationStore();
  const { showToast } = useAppStore();
  const { user, requireAuth } = useAuthStore();

  // Export CSV
  const handleExportCSV = () => {
    requireAuth('export CSV measurement records', () => {
      if (items.length === 0) {
        showToast('No measurement history to export', 'warning');
        return;
      }
      const headers = ['ID', 'Tool', 'Title', 'Value', 'Unit', 'NumericValue', 'Date', 'Details'];
      const rows = items.map((i) => [
        i.id,
        `"${i.tool}"`,
        `"${i.title}"`,
        `"${i.value}"`,
        `"${i.unit}"`,
        i.rawNumericValue,
        `"${new Date(i.timestamp).toISOString()}"`,
        `"${i.details || ''}"`,
      ]);

      const csvContent = [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
      const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.setAttribute('download', `MeasureX_Report_${Date.now()}.csv`);
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      showToast('Exported CSV measurement data!', 'success');
    });
  };

  // Export PDF Report using jsPDF
  const handleExportPDF = () => {
    requireAuth('generate official PDF engineering reports', () => {
      try {
        const doc = new jsPDF();
        doc.setFont('helvetica');

        // Header
        doc.setFillColor(67, 133, 232);
        doc.rect(0, 0, 210, 26, 'F');
        doc.setTextColor(255, 255, 255);
        doc.setFontSize(16);
        doc.text('MeasureX - Certified Measurement Report', 14, 16);

        // Metadata
        doc.setTextColor(50, 50, 50);
        doc.setFontSize(10);
        doc.text(`Certified Engineer: ${user?.name || 'Authorized Metrologist'} (${user?.plan?.toUpperCase()} Plan)`, 14, 34);
        doc.text(`Generated: ${new Date().toLocaleString()} | Email: ${user?.email || 'N/A'}`, 14, 40);
        doc.text(`Calibration Profile: ${profile.name} (${(profile.pixelsPerMm * 25.4).toFixed(1)} DPI)`, 14, 46);
        doc.text(`Calibration Status: ${profile.isCalibrated ? 'VERIFIED PHYSICAL STANDARD' : 'UNCALIBRATED ESTIMATE'}`, 14, 52);

        // Separator
        doc.setDrawColor(200, 200, 200);
        doc.line(14, 56, 196, 56);

        // Measurement Records
        doc.setFontSize(12);
        doc.setTextColor(29, 41, 64);
        doc.text('Measurement Records', 14, 64);

        let y = 72;
        items.forEach((item, index) => {
          if (y > 270) {
            doc.addPage();
            y = 20;
          }
          doc.setFontSize(10);
          doc.setFont('helvetica', 'bold');
          doc.text(`${index + 1}. [${item.tool}] ${item.title}: ${item.value}`, 16, y);
          doc.setFont('helvetica', 'normal');
          doc.setFontSize(8);
          doc.setTextColor(100, 100, 100);
          doc.text(`${new Date(item.timestamp).toLocaleString()} | ${item.details || 'Standard verification'}`, 20, y + 5);
          doc.setTextColor(50, 50, 50);
          y += 12;
        });

        // Footer
        doc.setFontSize(8);
        doc.setTextColor(150, 150, 150);
        doc.text('Generated by MeasureX - Universal Digital Measurement Platform', 14, 285);

        doc.save(`MeasureX_Technical_Report_${Date.now()}.pdf`);
        showToast('Generated Official PDF Measurement Report!', 'success');
      } catch (e) {
        console.error(e);
        showToast('Error generating PDF report', 'warning');
      }
    });
  };

  // Export JSON Backup
  const handleExportJSON = () => {
    requireAuth('export JSON project archive', () => {
      const backup = {
        app: 'MeasureX',
        version: '1.0.0',
        exportDate: new Date().toISOString(),
        author: user,
        calibration: profile,
        projects,
        history: items,
      };
      const blob = new Blob([JSON.stringify(backup, null, 2)], { type: 'application/json' });
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.setAttribute('download', `MeasureX_Full_Backup_${Date.now()}.json`);
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      showToast('Exported full JSON project workspace!', 'success');
    });
  };

  return (
    <div className="w-full max-w-5xl mx-auto flex flex-col gap-6 pb-12 select-none">
      {/* Header */}
      <div className="p-8 rounded-3xl bg-white/90 border border-[#DCE5F2] shadow-glass flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 backdrop-blur-xl">
        <div>
          <div className="flex items-center gap-2 mb-1">
            <span className="p-2 rounded-xl bg-blue-100 text-[#4385E8]">
              <Download className="w-5 h-5" />
            </span>
            <h1 className="text-2xl font-extrabold text-[#1D2940]">Export Center</h1>
          </div>
          <p className="text-sm text-[#66758D]">
            Export calibrated engineering reports, structured spreadsheets, and portable project archives.
          </p>
        </div>
      </div>

      {/* Export Options Grid */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
        {/* PDF Option */}
        <div className="p-6 rounded-3xl bg-white border border-[#DCE5F2] shadow-sm flex flex-col justify-between h-[260px] group hover:border-[#4385E8]/40 transition-all">
          <div>
            <div className="w-12 h-12 rounded-2xl bg-red-50 text-red-600 flex items-center justify-center mb-4">
              <FileText className="w-6 h-6" />
            </div>
            <h3 className="font-bold text-base text-[#1D2940] mb-1">Official PDF Report</h3>
            <p className="text-xs text-[#66758D] leading-relaxed">
              Complete engineering report with calibration metadata, timestamped coordinates, and readings.
            </p>
          </div>

          <button
            onClick={handleExportPDF}
            className="w-full py-2.5 rounded-xl bg-gradient-to-r from-red-500 to-rose-600 text-white font-bold text-xs shadow-md shadow-red-500/20 hover:scale-[1.02] active:scale-[0.98] transition-all flex items-center justify-center gap-2"
          >
            <Download className="w-4 h-4" />
            <span>Export PDF Document</span>
          </button>
        </div>

        {/* CSV Option */}
        <div className="p-6 rounded-3xl bg-white border border-[#DCE5F2] shadow-sm flex flex-col justify-between h-[260px] group hover:border-[#16A078]/40 transition-all">
          <div>
            <div className="w-12 h-12 rounded-2xl bg-emerald-50 text-emerald-600 flex items-center justify-center mb-4">
              <FileSpreadsheet className="w-6 h-6" />
            </div>
            <h3 className="font-bold text-base text-[#1D2940] mb-1">Spreadsheet CSV</h3>
            <p className="text-xs text-[#66758D] leading-relaxed">
              Raw comma-separated tabular data suitable for Excel, Google Sheets, Python, and MATLAB.
            </p>
          </div>

          <button
            onClick={handleExportCSV}
            className="w-full py-2.5 rounded-xl bg-gradient-to-r from-emerald-500 to-[#16A078] text-white font-bold text-xs shadow-md shadow-emerald-500/20 hover:scale-[1.02] active:scale-[0.98] transition-all flex items-center justify-center gap-2"
          >
            <Download className="w-4 h-4" />
            <span>Export CSV Dataset</span>
          </button>
        </div>

        {/* JSON Project Backup */}
        <div className="p-6 rounded-3xl bg-white border border-[#DCE5F2] shadow-sm flex flex-col justify-between h-[260px] group hover:border-[#8064E8]/40 transition-all">
          <div>
            <div className="w-12 h-12 rounded-2xl bg-purple-50 text-[#8064E8] flex items-center justify-center mb-4">
              <Code className="w-6 h-6" />
            </div>
            <h3 className="font-bold text-base text-[#1D2940] mb-1">Project JSON Archive</h3>
            <p className="text-xs text-[#66758D] leading-relaxed">
              Full workspace backup including calibration profiles, plotted points, projects, and history.
            </p>
          </div>

          <button
            onClick={handleExportJSON}
            className="w-full py-2.5 rounded-xl bg-gradient-to-r from-[#4385E8] to-[#8064E8] text-white font-bold text-xs shadow-md shadow-brand-blue/20 hover:scale-[1.02] active:scale-[0.98] transition-all flex items-center justify-center gap-2"
          >
            <Download className="w-4 h-4" />
            <span>Export JSON Backup</span>
          </button>
        </div>
      </div>
    </div>
  );
};
